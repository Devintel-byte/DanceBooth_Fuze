# Moves old build output, dev caches and the retired Maltina files to the
# Recycle Bin (nothing is deleted permanently), so `pnpm dev` and `pnpm build`
# start from the current FUZE Power Stage source.
#
# Run from the project folder:  scripts\clean-old-builds.bat
# (or: powershell -ExecutionPolicy Bypass -File scripts\clean-old-builds.ps1)
#
# Not touched: your booth data in %APPDATA% (settings, player numbers, records).
# The new app copies it from the old Maltina folder on first start.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName Microsoft.VisualBasic
$root = Split-Path -Parent $PSScriptRoot

$items = @(
  # Build output and dev caches (all regenerated by pnpm dev / pnpm build)
  'apps\desktop\out',
  'apps\desktop\.vite',
  'apps\desktop\test-results',
  'apps\desktop\node_modules\.vite',
  'node_modules\.vite',
  '.booth-data',
  # Retired Maltina content
  'assets\profiles\maltina.json',
  'assets\branding\maltina.png',
  'assets\routines\maltina-theme.json',
  'assets\audio\maltina-theme.wav',
  'assets\audio\source\maltina_theme_song.mp3',
  # Old Maltina-branded screenshots (FUZE screenshots replace them)
  'docs\screenshots\01-attract.png',
  'docs\screenshots\02-mode-select.png',
  'docs\screenshots\03-character-select.png',
  'docs\screenshots\03b-name-entry.png',
  'docs\screenshots\03c-song-picker.png',
  'docs\screenshots\04-calibration.png',
  'docs\screenshots\05-playing.png',
  'docs\screenshots\06-results.png',
  'docs\screenshots\07-operator.png',
  'docs\screenshots\08-leaderboard.png',
  'docs\screenshots\09-duo-calibration.png',
  'docs\screenshots\10-duo-playing.png'
)

$moved = 0
foreach ($rel in $items) {
  $p = Join-Path $root $rel
  if (Test-Path -LiteralPath $p -PathType Container) {
    [Microsoft.VisualBasic.FileIO.FileSystem]::DeleteDirectory($p, 'OnlyErrorDialogs', 'SendToRecycleBin')
    Write-Host "recycled  $rel\"
    $moved++
  } elseif (Test-Path -LiteralPath $p -PathType Leaf) {
    [Microsoft.VisualBasic.FileIO.FileSystem]::DeleteFile($p, 'OnlyErrorDialogs', 'SendToRecycleBin')
    Write-Host "recycled  $rel"
    $moved++
  }
}
if ($moved -eq 0) { Write-Host 'Nothing old left to clean.' }
else { Write-Host "`n$moved item(s) moved to the Recycle Bin. Restore from there if you need any of them." }
Write-Host "`nNext: pnpm install, pnpm setup:assets, pnpm dev"
